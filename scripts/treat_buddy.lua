-- Смещение Part0 -> Part1 сустава при заданном Transform.
-- Motor6D: Part1 = Part0 * C0 * Transform * C1^-1
-- AnimationConstraint (руки DOORS): Attachment1 = Attachment0 * Transform
local function jointOffset(j, transform)
    if j:IsA("Motor6D") then
        return j.C0 * transform * j.C1:Inverse()
    end
    local a0, a1 = j.Attachment0, j.Attachment1
    if not (a0 and a1) then return nil end
    return a0.CFrame * transform * a1.CFrame:Inverse()
end

local function jointPart0(j)
    if j:IsA("Motor6D") then return j.Part0 end
    return j.Attachment0 and j.Attachment0.Parent
end

-- Где в мире окажутся кулак и Handle при этих Transform руки (считаем сами, а не
-- читаем CFrame деталей: те обновятся только после кадра и бадди отставал бы от руки)
local function armWorld(out)
    local sh, el, wr, hm = joints.RightUpperArm, joints.RightLowerArm, joints.RightHand, joints.Handle
    if not (sh and el and wr and hm and sh.Parent and el.Parent and wr.Parent and hm.Parent) then return nil end
    local base = jointPart0(sh)
    if not base then return nil end
    local function tr(name, j) return out[name] or j.Transform end
    local o1 = jointOffset(sh, tr("RightUpperArm", sh))
    local o2 = jointOffset(el, tr("RightLowerArm", el))
    local o3 = jointOffset(wr, tr("RightHand", wr))
    local o4 = jointOffset(hm, tr("Handle", hm))
    if not (o1 and o2 and o3 and o4) then return nil end
    local hand = base.CFrame * o1 * o2 * o3
    return hand, hand * o4
end

local fkChecked = false
local fkFallback = false

-- Transform сустава бадди, чтобы его корпус оказался в мировой позе worldCF
local function torsoTransformFor(handleW, worldCF)
    local bj = joints.Buddy_Torso
    return (handleW * bj.C0):Inverse() * worldCF * bj.C1
end

-- Один раз проверяем свой расчёт руки по её реальному положению с прошлого кадра;
-- если не сходится — дальше берём положение деталей из игры (отстаёт на кадр, но верно)
local function checkFk()
    if not fkChecked and lastOut.RightUpperArm then
        local _, prevHandle = armWorld(lastOut)
        local handle = joints.Handle and joints.Handle.Part1
        if prevHandle and handle then
            fkChecked = true
            local err = (prevHandle.Position - handle.Position).Magnitude
            fkFallback = err > 0.3
            print(("[TreatBuddy] Проверка расчёта руки: ошибка %.3f -> %s"):format(err,
                fkFallback and "беру положение руки из игры" or "считаю сам"))
        end
    end
end

-- Где левая кисть относительно UpperTorso при этих позах (чистый расчёт по суставам)
local function leftHandLocalFor(pose)
    local o1 = jointOffset(joints.LeftUpperArm, pose.LeftUpperArm)
    local o2 = jointOffset(joints.LeftLowerArm, pose.LeftLowerArm)
    local o3 = jointOffset(joints.LeftHand, pose.LeftHand)
    if not (o1 and o2 and o3) then return nil end
    return (o1 * o2 * o3).Position
end

-- ЛКМ: левая рука (позы из spec), наведённая на нужное место бадди
local function handPin(out, t, spec)
    local st = action
    local ls, le, lw = joints.LeftUpperArm, joints.LeftLowerArm, joints.LeftHand
    if not (ls and le and lw and ls.Parent and le.Parent and lw.Parent) then return end

    -- в первый кадр запоминаем, как левую руку держала игра — из этой позы и уходим, и в неё возвращаемся
    if not st.leftBase then
        st.leftBase = {}
        for _, name in ipairs(LEFT_ARM) do st.leftBase[name] = joints[name].Transform end
    end
    local armW = spec.armW(t)
    local pose = spec.pose(t)
    for _, name in ipairs(LEFT_ARM) do
        out[name] = st.leftBase[name]:Lerp(pose[name], armW)
    end
    checkFk()
    if fkFallback or armW <= 0 then return end

    local base = jointPart0(ls)
    local bj = joints.Buddy_Torso
    local _, handleW = armWorld(out)
    if not (base and bj and bj.Parent and handleW) then return end

    -- точка касания ладони (среднее по позам spec.contact), в осях UpperTorso
    if st.contactLocal == nil then
        local sum, n = Vector3.zero, 0
        for _, p in ipairs(spec.contact()) do
            local pos = leftHandLocalFor(p)
            if pos then sum += pos; n += 1 end
        end
        st.contactLocal = n > 0 and sum / n or false
    end
    if not st.contactLocal then return end

    -- Поворачиваем всю левую руку в плече так, чтобы точка касания пришлась куда надо на бадди
    local shoulder = base.CFrame * (ls:IsA("Motor6D") and ls.C0 or ls.Attachment0.CFrame)
    local pivot = shoulder.Position
    local contact = base.CFrame * st.contactLocal
    local torsoW = handleW * bj.C0 * out.Buddy_Torso * bj.C1:Inverse()
    local target = torsoW * spec.target(t)
    local a, b = contact - pivot, target - pivot
    if a.Magnitude < 1e-3 or b.Magnitude < 1e-3 then return end
    local axis = a:Cross(b)
    if axis.Magnitude > 1e-4 then
        local angle = math.acos(math.clamp(a.Unit:Dot(b.Unit), -1, 1))
        local rw = CFrame.fromAxisAngle(axis.Unit, angle * armW)
        local q = shoulder.Rotation:Inverse() * rw * shoulder.Rotation
        out.LeftUpperArm = q * out.LeftUpperArm
    end

    -- рука короче/длиннее, чем нужно: чуть подаём бадди к ладони (не больше 0.6)
    local stick = spec.stick(t)
    local diff = math.clamp(b.Magnitude - a.Magnitude, -0.6, 0.6)
    if stick > 0 and math.abs(diff) > 0.01 then
        local shift = -b.Unit * diff * stick
        out.Buddy_Torso = torsoTransformFor(handleW, CFrame.new(shift) * torsoW)
    end
end

-- hold: корпус висит за капюшон под кулаком и качается маятником от движений руки
local function pinTorso(out, t, dt)
    local st = action
    if st.anim.hand then
        handPin(out, t, st.anim.hand)
        return
    end
    local bj = joints.Buddy_Torso
    if not (bj and bj.Parent) then return end
    local handW, handleW = armWorld(out)
    if not handW then return end

    checkFk()
    if fkFallback then
        local handle = joints.Handle.Part1
        local hand = joints.Handle.Part0
        if not (handle and hand) then return end
        handleW, handW = handle.CFrame, hand.CFrame
    end

    local grip = handW.Position
    local cam = workspace.CurrentCamera
    -- лицом к игроку, вертикально
    local toCam = cam and (cam.CFrame.Position - grip) or -handW.LookVector
    toCam = Vector3.new(toCam.X, 0, toCam.Z)
    if toCam.Magnitude < 1e-3 then toCam = Vector3.new(0, 0, -1) end
    local facing = CFrame.lookAt(Vector3.zero, toCam.Unit)

    local held
    if st.anim.pin == "hold" then
        -- маятник: рывки кулака раскачивают тело, сила тяжести возвращает
        local sw = st.swing
        if not sw then
            sw = { r = 0, f = 0.35, vr = 0, vf = 0, p = grip, v = Vector3.zero, a = Vector3.zero }
            st.swing = sw
        end
        dt = math.clamp(dt, 1 / 240, 1 / 20)
        local v = (grip - sw.p) / dt
        local a = (v - sw.v) / dt
        sw.p, sw.v = grip, v
        if a.Magnitude > PENDULUM.MAX_ACCEL then a = a.Unit * PENDULUM.MAX_ACCEL end
        sw.a = sw.a:Lerp(a, math.min(1, dt * 20))
        local ar = sw.a:Dot(facing.RightVector)
        local af = -sw.a:Dot(facing.LookVector) -- вдоль локальной +Z
        -- сам брыкается — немного раскачивает себя
        local kick = sin(t * TAU * 4) * shakeAmount(t, st) * 4
        local L, G = PENDULUM.LENGTH, PENDULUM.GRAVITY
        sw.vr += ((-ar - G * sin(sw.r)) / L + kick - PENDULUM.DAMPING * sw.vr) * dt
        sw.vf += ((af - G * sin(sw.f)) / L - PENDULUM.DAMPING * sw.vf) * dt
        sw.r = math.clamp(sw.r + sw.vr * dt, -PENDULUM.MAX_ANGLE, PENDULUM.MAX_ANGLE)
        sw.f = math.clamp(sw.f + sw.vf * dt, -PENDULUM.MAX_ANGLE, PENDULUM.MAX_ANGLE)
        local twist = rad(10) * S(t, 2.3)
        local worldCF = CFrame.new(grip) * facing * CFrame.Angles(sw.f, twist, sw.r) * CFrame.new(-HOOD_GRIP)
        st.heldW = worldCF
        held = torsoTransformFor(handleW, worldCF)
        -- рука поднимается и подхватывает: тело плавно «приезжает» под кулак
        out.Buddy_Torso = out.Buddy_Torso:Lerp(held, smooth(t / 0.3))
    elseif st.anim.pin == "release" and st.freezeW then
        -- кулак разжат: миг висит там же, потом падает на ладонь (ускоряясь)
        held = torsoTransformFor(handleW, st.freezeW)
        local fall = 0
        if t > RELEASE_HANG then
            fall = math.clamp((t - RELEASE_HANG) / (RELEASE_FALL - RELEASE_HANG), 0, 1) ^ 2
        end
        out.Buddy_Torso = held:Lerp(out.Buddy_Torso, fall)
    end
end

connect(RunService.Stepped, function(_, dt)
    if not (equipped and tool) then return end
    local now = os.clock()

    -- сустав руки с предметом появляется чуть позже экипировки — ищем, пока не найдём
    if now >= nextRebind and not (joints.Handle and joints.Handle.Parent and joints.Buddy_Torso and joints.Buddy_Torso.Parent) then
        nextRebind = now + 0.2
        rebindJoints()
    end

    -- 1) покой (если не заменяем его — начинаем от позы покоя)
    local idleD = {}
    if CONFIG.REPLACE.idle then
        ANIMS.idle.pose(((now - idleStart) * CONFIG.SPEED) % ANIMS.idle.length, idleD)
    end

    -- 2) действие поверх покоя с весом w: в начале (fadeIn) вес плавно растёт,
    --    в конце (fadeOut) плавно уходит в 0 — бадди перетекает в покой, а не прыгает
    local actD, w, actT = nil, 0, 0
    if action then
        local a = action.anim
        local t = (now - action.start) * CONFIG.SPEED - (a.delay or 0)
        if not a.loop and t >= a.length then
            restoreLeftArm(action)
            action = nil
        elseif t >= 0 then
            w = 1
            if a.fadeIn then w = smooth(t / a.fadeIn) end
            if not a.loop and a.fadeOut then
                local left = a.length - t
                if left < a.fadeOut then
                    if not action.idleReset then
                        -- покой начинаем заново: его начало — почти поза покоя, переход мягкий
                        action.idleReset = true
                        idleStart = now
                        ANIMS.idle.pose(0, idleD)
                    end
                    w = math.min(w, smooth(left / a.fadeOut))
                end
            end
            actD, actT = {}, t
            a.pose(t, actD, action)
            -- звуки, чьё время прошло с прошлого кадра
            local prevT = action.lastT or -1
            if a.sounds then
                for _, e in ipairs(a.sounds) do
                    if prevT < e[1] and t >= e[1] then playSound(e[2], e[3]) end
                end
            end
            if a.soundTick then a.soundTick(action, prevT, t) end
            action.lastT = t
        end
    end

    -- если ничего своего не играет (idle выключен), суставы не трогаем
    if not CONFIG.REPLACE.idle and not action and not blend then return end

    -- 3) переход из прошлой позы, когда одна анимация сменила другую
    local alpha = 1
    if blend then
        alpha = smooth((now - blend.start) / CONFIG.BLEND)
        if alpha >= 1 then blend = nil end
    end

    local out = {}
    for name in pairs(REST) do
        local cf = compose(name, idleD[name])
        if actD and w > 0 then
            cf = cf:Lerp(compose(name, actD[name]), w)
        end
        local from = blend and blend.from[name]
        if from then cf = from:Lerp(cf, alpha) end
        out[name] = cf
    end

    -- 4) за капюшон: корпус ставим под кулак (после руки — она уже посчитана)
    if action and actD and action.anim.pin and out.Buddy_Torso then
        pinTorso(out, actT, dt)
    end


    local armBusy = next(passthrough) ~= nil
    for name, cf in pairs(out) do
        local j = joints[name]
        if j and j.Parent and not (armBusy and CHARACTER_JOINTS[name]) then
            j.Transform = cf
            lastOut[name] = cf
        end
    end
end)

