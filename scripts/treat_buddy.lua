        resetCharacterJoints()
        equipped = false
        clearState()
    end))
    table.insert(toolConns, t.AncestryChanged:Connect(function()
        if not t:IsDescendantOf(game) then
            for _, c in ipairs(toolConns) do c:Disconnect() end
            toolConns, tool, equipped = {}, nil, false
        end
    end))

    local function onTrack(track)
        local name = track.Animation and animNames[track.Animation.AnimationId]
        if not name then return end
        local ours = GAME_TO_OURS[name]
        if not (ours and CONFIG.REPLACE[ours]) then
            -- чужая анимация бадди (whack, item...): пока играет, рука персонажа — игры
            if equipped then
                passthrough[track] = true
                track.Stopped:Connect(function() passthrough[track] = nil end)
                task.delay(track.Length + 0.5, function() passthrough[track] = nil end)
            end
            return
        end
        if not equipped then return end
        local isClick = ours == "lmb" or ours == "rmb"
        if isClick and os.clock() - equipTime > 0.4 then
            -- клик: сразу (игра иногда сама мгновенно обрывает свой трек осмотра)
            track:Stop(0)
            press(ours)
        else
            -- при экипировке игра на миг запускает все анимации (подгрузка),
            -- поэтому глушим только те, что реально продолжают играть
            task.delay(0.05, function()
                if equipped and track.IsPlaying and track.WeightTarget > 0.01 then
                    track:Stop(0)
                    if isClick then press(ours) end
                end
            end)
        end
    end

    local function watchAnimator(animator)
        table.insert(toolConns, animator.AnimationPlayed:Connect(onTrack))
        -- скрипт запустили, когда бадди уже в руках: глушим то, что уже играет
        if equipped then
            for _, track in ipairs(animator:GetPlayingAnimationTracks()) do
                local name = track.Animation and animNames[track.Animation.AnimationId]
                local ours = name and GAME_TO_OURS[name]
                if ours and CONFIG.REPLACE[ours] then track:Stop(0) end
            end
        end
    end
    for _, root in ipairs({ player.Character, t }) do
        if root then
            for _, d in ipairs(root:GetDescendants()) do
                if d:IsA("Animator") then watchAnimator(d) end
            end
            table.insert(toolConns, root.DescendantAdded:Connect(function(d)
                if d:IsA("Animator") then watchAnimator(d) end
            end))
        end
    end

    print("[TreatBuddy] Подключён к " .. t:GetFullName() .. (equipped and " (в руках)" or ""))
end

local warnedSkin = false
local function setup()
    local t, wrong = findBuddy()
    if t then
        if t ~= tool then bindTool(t) end
    elseif wrong and not warnedSkin then
        warnedSkin = true
        warn("[TreatBuddy] Бадди другого скина: " .. tostring(wrong:GetAttribute("ToolSkin"))
            .. ". Позы сняты со скина " .. CONFIG.SKIN .. " — поставь CONFIG.SKIN = nil, чтобы всё равно включить")
        notify("Это не тот бадди: " .. tostring(wrong:GetAttribute("ToolSkin")))
    end
end

local function watchContainer(c)
    connect(c.ChildAdded, function(child)
        if child ~= tool and isBuddy(child) then task.defer(setup) end
    end)
end

local function onCharacter(character)
    character:WaitForChild("HumanoidRootPart", 10)
    watchContainer(character)
    watchContainer(player:WaitForChild("Backpack"))
    task.wait(0.5) -- даём игре выдать предметы
    tool = nil
    setup()
end

if player.Character then task.spawn(onCharacter, player.Character) end
connect(player.CharacterAdded, onCharacter)

