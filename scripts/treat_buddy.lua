local PET_JOINTS = { "RightUpperArm", "RightLowerArm", "LeftUpperArm", "LeftLowerArm", "LeftHand" }
local PET_CF = {} -- [сустав] = { CFrame по кадрам }
for _, name in ipairs(PET_JOINTS) do
    local list = {}
    for i, v in ipairs(PET_DATA[name]) do
        list[i] = P(v[1], v[2], v[3], v[4], v[5], v[6])
    end
    PET_CF[name] = list
end
local PET_LENGTH = PET_DATA.t[#PET_DATA.t]

-- номер кадра слева от t и доля пути до следующего
local function petFrame(t)
    local ts = PET_DATA.t
    local n = #ts
    if t <= ts[1] then return 1, 0 end
    if t >= ts[n] then return n - 1, 1 end
    local lo, hi = 1, n
    while hi - lo > 1 do
        local mid = (lo + hi) // 2
        if ts[mid] <= t then lo = mid else hi = mid end
    end
    return lo, (t - ts[lo]) / (ts[hi] - ts[lo])
end

-- поза сустава руки из анимации Стиви в момент t
local function petSample(name, t)
    local i, f = petFrame(t)
    local list = PET_CF[name]
    return list[i]:Lerp(list[i + 1], f)
end

-- одно число из данных Стиви (например, поворот предплечья — по нему видно взмах руки)
local function petValue(name, index, t)
    local i, f = petFrame(t)
    local list = PET_DATA[name]
    return list[i][index] + (list[i + 1][index] - list[i][index]) * f
end

