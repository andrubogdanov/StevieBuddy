-- моменты взмахов ладони Стиви (предплечье разворачивается) — на них звук поглаживания
local PET_STROKES = {}
do
    local ts, v = PET_DATA.t, PET_DATA.LeftLowerArm
    local lastKept = nil
    for i = 2, #ts - 1 do
        local a, b, c = v[i - 1][5], v[i][5], v[i + 1][5]
        local extreme = (b < a and b <= c) or (b > a and b >= c)
        if extreme and ts[i] >= PET_TOUCH_FROM - 0.1 and ts[i] <= PET_TOUCH_TO
            and (lastKept == nil or math.abs(b - lastKept) > 30) then
            table.insert(PET_STROKES, ts[i])
            lastKept = b
        end
    end
end

