local function isLocalFile(value)
    return type(value) == "string" and value ~= ""
        and not value:match("^%d+$") and not value:match("^rbx") and not value:match("^https?://")
end

local function fileExists(path)
    return isfile ~= nil and select(2, pcall(isfile, path)) == true
end

local function soundList(value)
    return type(value) == "table" and value or { value }
end

-- докачиваем недостающие файлы в workspace/ASSET_FOLDER
local function downloadSounds()
    if not (makefolder and writefile) then return end
    for _, value in pairs(CONFIG.SOUNDS) do
        for _, file in ipairs(soundList(value)) do
            if isLocalFile(file) then
                local path = CONFIG.ASSET_FOLDER .. "/" .. file
                local dir = ""
                for part in path:gmatch("([^/]+)/") do
                    dir = dir .. part
                    if not (isfolder and isfolder(dir)) then pcall(makefolder, dir) end
                    dir = dir .. "/"
                end
                if CONFIG.ASSETS_URL ~= "" and (CONFIG.REDOWNLOAD or not fileExists(path)) then
                    local ok, data = pcall(game.HttpGet, game, CONFIG.ASSETS_URL .. file)
                    if ok and data and #data > 100 and not data:match("^404") then
                        writefile(path, data)
                        print("[TreatBuddy] Скачан " .. path)
                    else
                        warn("[TreatBuddy] Не удалось скачать " .. CONFIG.ASSETS_URL .. file)
                    end
                end
            end
        end
    end
end
pcall(downloadSounds)

local function resolveSound(value)
    if value == nil or value == "" then return nil end
    if type(value) == "number" or tostring(value):match("^%d+$") then
        return "rbxassetid://" .. value
    end
    if not isLocalFile(value) then return value end
    local path = CONFIG.ASSET_FOLDER .. "/" .. value
    if fileExists(path) and getcustomasset then
        local ok, url = pcall(getcustomasset, path)
        if ok then return url end
    end
    return nil
end

local SOUND_IDS = {} -- [имя] = { ссылки }
for name, value in pairs(CONFIG.SOUNDS) do
    local list = {}
    for _, v in ipairs(soundList(value)) do
        local id = resolveSound(v)
        if id then table.insert(list, id) end
    end
    if #list > 0 then
        SOUND_IDS[name] = list
    else
        warn("[TreatBuddy] Нет звука " .. name)
    end
end

-- несколько Sound на каждый звук, чтобы быстрые повторы не обрывали друг друга
local soundPool = {}
local function playSound(name, speed)
    local ids = SOUND_IDS[name]
    if not ids then return end
    local pool = soundPool[name]
    if not pool then
        pool = { i = 0 }
        for k = 1, 3 do
            local s = Instance.new("Sound")
            s.Name = "TreatBuddy_" .. name .. k
            s.Volume = CONFIG.SOUND_VOLUME
            s.Parent = game:GetService("SoundService")
            pool[k] = s
        end
        soundPool[name] = pool
    end
    pool.i = pool.i % 3 + 1
    local s = pool[pool.i]
    s.SoundId = ids[math.random(#ids)]
    -- каждый раз чуть другой тон, чтобы не звучало одинаково
    s.PlaybackSpeed = (speed or 1) * (0.94 + math.random() * 0.12)
    s.TimePosition = 0
    s:Play()
end

---------------------------------------------------------------- математика

local rad, sin, pi = math.rad, math.sin, math.pi
local TAU = pi * 2

-- смещение: позиция + поворот в градусах (сначала Y, потом X, потом Z)
local function D(px, py, pz, rx, ry, rz)
    return CFrame.new(px, py, pz) * CFrame.fromOrientation(rad(rx), rad(ry), rad(rz))
end

-- поза покоя в формате записи: pos(...) rot(...) из cf:ToOrientation()
local P = D

-- синус с периодом в секундах и сдвигом фазы (в долях периода)
local function S(t, period, phase)
    return sin(TAU * (t / period + (phase or 0)))
end

-- кривая по ключам { {время, значение, [сглаживание]} }:
-- "out" — быстрый старт, "in" — быстрый конец, "linear", по умолчанию плавно с двух сторон
local function K(t, keys)
    if t <= keys[1][1] then return keys[1][2] end
    for i = 2, #keys do
        local b = keys[i]
        if t <= b[1] then
            local a = keys[i - 1]
            local x = (t - a[1]) / (b[1] - a[1])
            local style = b[3]
            if style == "out" then
                x = 1 - (1 - x) ^ 3
            elseif style == "in" then
                x = x ^ 3
            elseif style ~= "linear" then
                x = x * x * (3 - 2 * x)
            end
            return a[2] + (b[2] - a[2]) * x
        end
    end
    return keys[#keys][2]
end

local function smooth(x)
    x = math.clamp(x, 0, 1)
    return x * x * (3 - 2 * x)
end

-- 0 -> 1 -> 0 на отрезке [a, b] (горб синуса), вне отрезка 0
local function bump(t, a, b)
    if t <= a or t >= b then return 0 end
    return sin((t - a) / (b - a) * pi)
end

