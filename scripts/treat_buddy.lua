    for s, vol in pairs(mutedSounds) do
        if s.Parent then s.Volume = vol end
    end
    mutedSounds = {}
    for _, d in ipairs(t:GetDescendants()) do
        if d:IsA("Sound") and CONFIG.MUTE_GAME_SOUNDS[d.Name] then
            mutedSounds[d] = d.Volume
            d.Volume = 0
        end
    end

    local animNames = {} -- [AnimationId] = имя из папки Animations
    local folder = t:FindFirstChild("Animations")
    if folder then
        for _, a in ipairs(folder:GetChildren()) do
            if a:IsA("Animation") then animNames[a.AnimationId] = a.Name end
        end
    end

    table.insert(toolConns, t.Equipped:Connect(function()
        equipped = true
        equipTime = os.clock()
        idleStart = os.clock()
        joints, nextRebind = {}, 0
        clearState()
        lastPress = { name = nil, time = 0 }
        press("equip")
    end))
