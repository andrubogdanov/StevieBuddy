local function startAction(name)
    local anim = ANIMS[name]
    local prev = action
    restoreLeftArm(prev)
    if anim.noBlendIn then
        blend, lastOut = nil, {}
    elseif anim.delay and not prev then
        -- из покоя такая анимация сама плавно входит (fadeIn), покой пока продолжается
        blend = nil
    else
        -- плавно из той позы, что сейчас на экране (покой или прошлая анимация)
        local from = {}
        for k, v in pairs(lastOut) do from[k] = v end
        blend = { from = from, start = os.clock() }
    end
    action = { name = name, anim = anim, start = os.clock() }
    -- отпустили: бадди сначала остаётся там, где висел
    if name == "release" and prev and prev.heldW then
        action.freezeW = prev.heldW
    end
end

-- нажатие (по игровому треку): lmb / rmb / equip
local function press(button)
    if not (equipped and CONFIG.REPLACE[button]) then return end
    local now = os.clock()
    -- игра иногда запускает один и тот же трек дважды подряд — второй раз не считаем
    if lastPress.name == button and now - lastPress.time < 0.3 then return end
    lastPress = { name = button, time = now }

    if button == "equip" then
        holding = false
        startAction("equip")
    elseif button == "rmb" then
        holding = not holding
        startAction(holding and "hold" or "release")
    elseif button == "lmb" then
        if holding and action and action.name == "hold" then
            -- держим за капюшон: ЛКМ — потрясти
            action.shakeAt = (now - action.start) * CONFIG.SPEED
        else
            holding = false
            local order = CONFIG.LMB_ORDER
            local name
            if CONFIG.LMB_RANDOM and #order > 1 then
                repeat name = order[math.random(#order)] until name ~= lastLmb
            else
                lmbIndex = lmbIndex % #order + 1
                name = order[lmbIndex]
            end
            lastLmb = name
            startAction(ANIMS[name] and name or "pet")
        end
    end
end

