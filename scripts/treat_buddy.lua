-- ПКМ: держишь за капюшон и таскаешь. Анимация без конца, пока не отпустишь.
local function shakeAmount(t, st)
    -- сам иногда брыкается (каждые 4 с), плюс встряска по ЛКМ
    local auto = bump(t % 4, 2.8, 3.5)
    local manual = 0
    if st.shakeAt then manual = bump(t - st.shakeAt, 0, 0.7) end
    return math.max(auto, manual)
end

