local function rebindJoints()
    joints = {}
    if not tool then return end
    for _, d in ipairs(tool:GetDescendants()) do
        if d:IsA("Motor6D") and d.Part1 and REST[d.Part1.Name] then
            joints[d.Part1.Name] = d
        end
    end
    local char = player.Character
    if not char then return end
    local function charJoint(partName, jointName)
        local part = char:FindFirstChild(partName)
        local j = part and part:FindFirstChild(jointName)
        if j and (j:IsA("Motor6D") or j:IsA("AnimationConstraint")) then return j end
        return nil
    end
    joints.RightUpperArm = charJoint("RightUpperArm", "RightShoulder")
    joints.RightLowerArm = charJoint("RightLowerArm", "RightElbow")
    joints.RightHand = charJoint("RightHand", "RightWrist")
    -- левая рука — для поглаживания
    joints.LeftUpperArm = charJoint("LeftUpperArm", "LeftShoulder")
    joints.LeftLowerArm = charJoint("LeftLowerArm", "LeftElbow")
    joints.LeftHand = charJoint("LeftHand", "LeftWrist")
    local handle = tool:FindFirstChild("Handle")
    local hand = char:FindFirstChild("RightHand")
    if handle and hand then
        for _, d in ipairs(hand:GetChildren()) do
            if d:IsA("Motor6D") and d.Part1 == handle then joints.Handle = d end
        end
    end
end

-- левую руку анимирует игра; если мы её двигали и прервались — возвращаем как было
