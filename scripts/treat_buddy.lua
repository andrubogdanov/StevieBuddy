-- правая рука подаёт бадди навстречу левой (как у Стиви), w — насколько
local function presentRightArm(o, t, w)
    local rua = petSample("RightUpperArm", t) * PET_CF.RightUpperArm[1]:Inverse()
    local rla = petSample("RightLowerArm", t) * PET_CF.RightLowerArm[1]:Inverse()
    o.RightUpperArm = CFrame.identity:Lerp(rua, w)
    o.RightLowerArm = CFrame.identity:Lerp(rla, w)
